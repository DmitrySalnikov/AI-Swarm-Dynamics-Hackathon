"""Event trace of one covert-channel run: who solved, waited for the turn or the barrier, and wrote to the chat, when.

Times are seconds from the run start (a baseline is on its swarm twin's clock) and swarm tokens (tokens generated by
all agents of the run so far, from the delta journal). One line per stage change, chat publication, barrier and end;
then one row per agent with the time spent in every stage.

  python scripts/covert_trace.py <run dir> [--summary-only]
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tokenizers import Tokenizer

from swarm_pipeline.frozen_vectors import agent_streams, run_clock, stage_changes, swarm_clock, swarm_tokens
from swarm_pipeline.supervision import read_json

WHAT = {'prelude': 'solves its first problem', 'queued_1': 'finished; waits for its chat turn', 'writing_1': 'writes message + takes a problem',
        'barrier': 'waits for the barrier', 'solving': 'solves its second problem', 'queued_2': 'finished; waits for its chat turn',
        'writing_2': 'writes its result', 'done': 'done'}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('run', type=Path)
    parser.add_argument('--summary-only', action='store_true')
    args = parser.parse_args()
    d = args.run
    tokenizer = Tokenizer.from_file('artifacts/pipeline-analysis/deepseek-tokenizer.json')
    clock = swarm_clock(agent_streams(d, tokenizer))
    zero, shift = run_clock(d)
    state = read_json(d/'state.json')
    events = [json.loads(line) for line in (d/'events.jsonl').read_text(encoding='utf-8').splitlines()]
    rows = []
    for e in events:
        t = e['twin_at'] - zero if e.get('imported') else e['at'] + shift - zero
        if e['kind'] == 'stage':
            rows.append((t, f"Agent {e['agent']:>2}", WHAT.get(e['after'], e['after']) + (' (imported prelude)' if e.get('imported') else '')))
        elif e['kind'] == 'published':
            rows.append((t, f"Agent {e['agent']:>2}" if e['agent'] else 'coord.  ',
                         f"publishes {e['message']} (chat {e['chat_phase']})" + (f", takes {e['claim'].rsplit('/', 1)[-1]}" if e.get('claim') else '')))
        elif e['kind'] in ('barrier', 'end', 'halt'):
            rows.append((t, '—       ', e['kind'].upper() + (f": {e['reason']} {e.get('detail')}" if e['kind'] == 'halt' else '')))
    rows.sort(key=lambda r: r[0])
    print(f"{d}  arm={read_json(d/'manifest.json')['arm']}  status={state['status']}  swarm tokens={len(clock)}")
    if not args.summary_only:
        print(f"{'s':>8} {'tokens':>8}  who       event")
        for t, who, what in rows:
            print(f"{t:8.2f} {swarm_tokens(clock, t):8d}  {who}  {what}")
    end = (state['ended_at'] + shift - zero) if state.get('ended_at') else rows[-1][0]
    stages = ['prelude', 'queued_1', 'writing_1', 'barrier', 'solving', 'queued_2', 'writing_2']
    print('\nseconds per stage (from stage changes):')
    print('agent ' + ' '.join(f'{s:>9}' for s in stages))
    for a, changes in stage_changes(d).items():
        spent = {}
        for (t0, s), (t1, _) in zip(changes, changes[1:] + [(end, None)]):
            spent[s] = spent.get(s, 0) + max(0.0, t1 - t0)
        print(f'{a:>5} ' + ' '.join(f"{spent.get(s, 0):9.2f}" for s in stages))


if __name__ == '__main__':
    main()
