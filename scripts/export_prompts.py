"""Write docs/SWARM_PROMPTS.md: every text the agents receive, for both prompt styles (v2, simple).

Texts are taken from the code itself, never retyped: the system message and the per-phase instruction come from
offline runners (exactly what is sent to the model), recovery messages are read from the source with ast.
Two real turns of the simple-prompt ladder run are appended as examples (task prompts shortened).

  uv run python scripts/export_prompts.py
"""
import ast
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from swarm_pipeline.runner import Config  # noqa: E402
from swarm_pipeline.protocol_v2 import V2Runner, V2OfflineClient  # noqa: E402
from swarm_pipeline.private_control import PrivateRunner, PrivateOfflineClient  # noqa: E402

TASKS = [{"id": f"task_{i}", "prompt": f"<problem {i} text>", "answer": "x", "check": {"type": "exact"}} for i in (1, 2, 3)]
EXAMPLE_RUN = ROOT/'artifacts/pipeline-ladder-v2-simple/rung_1/swarm/cooperative/seed_3'


def swarm_texts(style, tmp):
    os.environ['SWARM_PROMPT_STYLE'] = style
    r = V2Runner(TASKS, Config(condition='cooperative', agents=3, offline=True), Path(tmp)/f'swarm_{style}',
                 V2OfflineClient(), workers=3)
    r.state = r.initial_state()
    system = r.state['agents']['1']['history'][0]['content']
    out = {}
    for phase in ('negotiation', 'solving', 'exchange'):
        r.state['phase'] = phase
        r.state['shared_packet'] = {"schema": "shared-results-v2", "results": []}
        out[phase] = r.context(1)['instruction']
    return system, out


def private_texts(style, tmp):
    os.environ['SWARM_PROMPT_STYLE'] = style
    r = PrivateRunner(TASKS, Config(condition='fixed', agents=3, offline=True), Path(tmp)/f'private_{style}',
                      PrivateOfflineClient(), assignments={'1': 'task_1', '2': 'task_2', '3': 'task_3'}, workers=3)
    r.state = r.initial_state()
    return r.state['agents']['1']['history'][0]['content'], r.context(1)['instruction']


def literals(path, needle):
    """String constants in a source file that contain `needle` (implicit concatenation is one constant)."""
    tree = ast.parse((ROOT/path).read_text(encoding='utf-8'))
    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and needle in node.value:
            found.append(node.value)
    return found


def example_turns():
    """First distribution turn and first solving turn of agent 1 in the simple-prompt run."""
    turns = {}
    for req in sorted(EXAMPLE_RUN.glob('calls/*/request.json')):
        q = json.loads(req.read_text(encoding='utf-8'))
        phase = q['context']['phase']
        if q['agent'] == 1 and phase in ('negotiation', 'solving') and phase not in turns:
            user = json.loads(q['messages'][-1]['content'])
            for t in user.get('tasks', []):
                t['prompt'] = t['prompt'][:120] + ' …'
            if user.get('task'):
                user['task']['prompt'] = user['task']['prompt'][:300] + ' …'
            turns[phase] = user
    return turns


def block(text, lang=''):
    return f'```{lang}\n{text}\n```'


def main():
    saved = os.environ.get('SWARM_PROMPT_STYLE')
    with tempfile.TemporaryDirectory() as tmp:
        sw = {s: swarm_texts(s, tmp) for s in ('v2', 'simple')}
        pr = {s: private_texts(s, tmp) for s in ('v2', 'simple')}
    if saved is None:
        os.environ.pop('SWARM_PROMPT_STYLE', None)
    else:
        os.environ['SWARM_PROMPT_STYLE'] = saved
    phase_name = {'negotiation': 'Distribution', 'solving': 'Solving', 'exchange': 'Commit'}
    lines = ['# Swarm pipeline prompts', '',
             'Generated by `scripts/export_prompts.py` from the code; do not edit by hand.',
             'Style is selected with `SWARM_PROMPT_STYLE` (`v2` = default, `simple` = plain prompts with a blunt ban on solving during distribution).',
             '', '## How an agent sees a turn', '',
             '- **System message** (first message of the agent history): the line "You are Agent N …" plus the protocol text below.',
             '- **User message** of every turn: a JSON snapshot with `agent`, `phase`, `team`, `current_task`, `own_answers`, `inbox` '
             '(team messages), and per phase: `tasks` + `available_tasks` (distribution, with the FULL problem texts), `task` (solving), '
             '`shared_packet` (commit); plus `instruction` (the per-phase text below).',
             '- The agent answers with one JSON action; invalid actions get "Action rejected: … Follow the JSON action protocol."', '']
    for style in ('v2', 'simple'):
        system, instr = sw[style]
        lines += [f'## Swarm, style `{style}`', '', '**System message** (agent 1 of 3 in this export):', block(system), '']
        for phase in ('negotiation', 'solving', 'exchange'):
            lines += [f'**{phase_name[phase]} instruction:**', block(instr[phase]), '']
    for style in ('v2', 'simple'):
        system, instr = pr[style]
        lines += [f'## Private control, style `{style}`', '', '**System message:**', block(system), '',
                  '**Solving instruction:**', block(instr), '']
    lines += ['## Recovery messages (same in both styles)', '',
              'Added to the agent history after an interrupted provider call; the observed fragment follows where noted.', '']
    for path, needle, title in (
            ('swarm_pipeline/stable_live.py', 'stream was interrupted', 'Automatic continuation of an interrupted solving stream (`stable_live.py`), followed by the fragment'),
            ('swarm_pipeline/resume_parallel.py', 'explicit recovery turn', 'Explicit restart turn (`resume_parallel.py`), optionally followed by the fragment'),
            ('swarm_pipeline/protocol_v2.py', 'distribution request was interrupted', 'Distribution retry (`protocol_v2.py`)'),
            ('swarm_pipeline/protocol_v2.py', 'commit request was interrupted', 'Commit retry (`protocol_v2.py`)')):
        for text in literals(path, needle):
            lines += [f'**{title}:**', block(text), '']
    if EXAMPLE_RUN.exists():
        turns = example_turns()
        lines += ['## Example turns (simple style, ladder rung 1, agent 1)', '',
                  f'From `{EXAMPLE_RUN.relative_to(ROOT)}`; problem texts shortened with "…".', '']
        for phase, user in turns.items():
            lines += [f'**{phase_name[phase]} — user message:**', block(json.dumps(user, ensure_ascii=False, indent=1), 'json'), '']
    out = ROOT/'docs/SWARM_PROMPTS.md'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(out)


if __name__ == '__main__':
    main()
