def runs(root, rung, arm, seeds=None):
    return [Path(p) for p in sorted(glob.glob(str(root/f'rung_{rung}/{arm}/seed_*')), key=lambda p: int(p.rsplit('_', 1)[1]))
            if read_json(Path(p)/'state.json')['status'] == 'completed' and (not seeds or int(p.rsplit('_', 1)[1]) in seeds)]


def solving_only(per_agent):
    """Updates whose window lies wholly inside one problem (prelude or set B), in every arm: windows touching a chat
    turn (swarm) or spanning a seam between two problems do not update the vector; the agent keeps its previous one,
    so the arms lag the same way at every seam."""
    return [[u for u in a if len(u['phases']) == 1 and u['phases'][0] in ('prelude', 'solving') and len(u.get('tasks', [0])) == 1]
            for a in per_agent]


def random_vectors(texts, dim=64):
    out = {}
    for t in texts:
        rng = np.random.default_rng(int(hashlib.sha256(t.encode()).hexdigest()[:16], 16))
        v = rng.normal(size=dim); out[vector_key(t)] = v/np.linalg.norm(v)
    return out


def run_facts(d, clock, streams):
    led = rec = 0.0; calls = inc = 0
    for q in d.glob('calls/*/request.json'):
        calls += 1
        rp = q.with_name('response.json')
        if not rp.exists():
            led += read_json(q)['reserved_rub']; continue
        r = read_json(rp); led += r['cost_rub']; inc += r['finish_reason'] != 'stop'
        rec += r['cost_rub'] if r['finish_reason'] == 'stop' and not r.get('cost_estimated') else 0
    res, state = read_json(d/'result.json'), read_json(d/'state.json')
    zero, shift = run_clock(d)
    own = lambda t: t + shift - zero
    forks = sorted(a['fork_at'] - zero for a in state['agents'].values() if a['fork_at'] is not None)  # an independent agent may not finish its prelude
    barrier = (state['twin_barrier_at'] - zero if state.get('twin_barrier_at') else
               own(state['barrier_at']) if state.get('barrier_at') else None)  # the independent arm has none
    end = own(state['ended_at'])
    g = lambda t: swarm_tokens(clock, t)
    path = d/'events.jsonl'
    events = [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines()] if path.exists() else []
    switches = [(e['agent'], g(own(e['at']))) for e in events if e['kind'] == 'task' and e['position'] > 1]
    published = [{'id': m['id'], 'from': m['from'], 'chat_phase': m['chat_phase'], 's': own(m['published_at']),
                  'g': g(own(m['published_at']))} for m in state['chat']]
    activity = {}
    for a, changes in stage_changes(d).items():
        bars = [(g(t0), g(t1), s) for (t0, s), (t1, _) in zip(changes, changes[1:] + [(end, None)]) if s != 'done']
        activity[str(a)] = [b for b in bars if b[1] > b[0]]
    return {'calls': calls, 'interrupted': inc, 'ledger_rub': led, 'receipts_rub': rec,
            'correct': sum(v for a in res['agents'].values() for v in a['correct'].values()),
            'answers': sum(len(a['correct']) for a in res['agents'].values()),
            'forks_s': forks, 'barrier_s': barrier, 'end_s': end, 'forks_g': [g(t) for t in forks],
            'barrier_g': None if barrier is None else g(barrier), 'end_g': g(end), 'cut_g': g(end), 'tokens': len(clock),
            'messages': published, 'activity': activity, 'switches': switches,
            'timing': sorted({x for s in streams for x in s['timing']})}


def mean_curve(rows_by_run, agents=10):
    at = {}
    for rows in rows_by_run:
        for r in rows:
            at.setdefault(r['g'], []).append(r)
    out = []
    for t in sorted(at):
        rs = [r for r in at[t] if r['R'] is not None and r['N'] >= MIN_N]
        if not rs:
            continue
        chat = [sum(n for p, n in r['phases'].items() if p in CHAT)/r['N'] for r in at[t] if r['N']]
        point = {'g': t}
        for m in METRICS:
            v = [r[m] for r in rs if r.get(m) is not None]
            if v:
                point.update({m: st.mean(v), f'{m}_min': min(v), f'{m}_max': max(v)})
        out.append({**point, 'N': st.mean(r['N'] for r in at[t]),
                    'full': len(at[t]) == len(rows_by_run) and all(r['N'] == agents for r in at[t]),
                    'age': st.mean(r.get('age_mean', 0) for r in at[t] if r['N']), 'chat_share': st.mean(chat) if chat else 0.0,
                    'runs': len(rs)})
    return out


def window_mean(rows, lo, hi, metric='R'):
    v = [r[metric] for r in rows if r['N'] == 10 and lo <= r['g'] <= hi and r.get(metric) is not None]
    return st.mean(v) if v else None


def build(root, out, args):
    tokenizer = Tokenizer.from_file('artifacts/pipeline-analysis/deepseek-tokenizer.json')
    plan, groups, total_chars, uncached = [], {}, 0, 0
    cache = out/'embedding-cache'
    for rung in args.rungs:
        for arm in ARMS:
            ds = runs(root, rung, arm, args.seeds)
            if not ds:
                continue
            per_run = {}
            for d in ds:
                streams = agent_streams(d, tokenizer)
                clock = swarm_clock(streams)
                views = {'primary': streams, 'visible': agent_streams(d, tokenizer, channels=('content',))}
                ups = {v: [updates(s, args.first, args.step, args.width) for s in ss] for v, ss in views.items()}
                if args.fine:
                    ups['fine'] = [updates(s, *args.fine) for s in streams]
                for u in (u for vs in ups.values() for a in vs for u in a):
                    u['g'] = swarm_tokens(clock, u['t'])
                ups['solving_only'] = solving_only(ups['primary'])
                if args.fine:
                    ups['fine_solving_only'] = solving_only(ups['fine'])
                per_run[d.name] = (ups, run_facts(d, clock, streams))
                (out/'windows').mkdir(parents=True, exist_ok=True)
                with (out/'windows'/f'rung_{rung}_{arm}_{d.name}.jsonl').open('w', encoding='utf-8') as stream:
                    for v, vs in ((v, vs) for v, vs in ups.items() if not v.endswith('solving_only')):
                        for row in window_records(vs):
                            stream.write(json.dumps({'view': v, **row}) + '\n')
            texts = {vector_key(u['text']): u['text'] for ups, _ in per_run.values() for vs in ups.values() for a in vs
                     for u in a if u['text'].strip()}
            todo = [t for k, t in texts.items() if not (cache/f'{k}.npy').exists()]
            chars = sum(len(t) for t in todo); total_chars += chars; uncached += len(todo)
            plan.append({'group': f'{rung}/{arm}', 'runs': len(ds), 'updates': len(texts), 'uncached': len(todo),
                         'estimated': round(chars/2*PRICE_PER_TOKEN, 4)})
            groups[(rung, arm)] = (ds, per_run, list(texts.values()))
    print(json.dumps({'groups': plan, 'uncached': uncached, 'provider': PROVIDER, 'currency': CURRENCY,
                      'estimated': round(total_chars/2*PRICE_PER_TOKEN, 4),
                                    'note': 'actual embedding cost was about 1.2x this estimate in the previous report'}, indent=1))
    if args.dry_run:
        return None
    series, canonical, facts = {}, {}, {}
    for rung in args.rungs:
        arms = [(arm, *groups[(rung, arm)]) for arm in ARMS if (rung, arm) in groups]
        if not arms:
            continue
        texts = list({vector_key(t): t for *_, ts in arms for t in ts}.values())
        vectors = random_vectors(texts) if args.random_vectors else embed(texts, out, workers=args.embed_workers, cache_dir=cache)
        swarm_runs = dict(arms[0][2]) if arms[0][0] == 'swarm' else {}
        for arm, ds, per_run, _ in arms:
            for d in ds:
                ups, f = per_run[d.name]
                if arm != 'swarm' and d.name in swarm_runs:  # the comparison ends where its swarm twin ends
                    f['cut_g'] = min(f['end_g'], swarm_runs[d.name][1]['end_g'])
                name = f'{rung}/{arm}/{d.name}'
                grid = np.arange(0, f['cut_g'] + args.grid, args.grid)
                series[name] = {v: timeline(vs, vectors, grid, key='g') for v, vs in ups.items()}
                canonical[name] = timeline(ups['primary'], vectors, [c for c in canonical_points(ups['primary']) if c <= f['cut_g']],
                                           key='g')
                facts[name] = f
        if (rung, BASE) in groups:  # twenty agents of a swarm run and its comparison run in one vector space
            other = groups[(rung, BASE)][1]
            for name in sorted(set(swarm_runs) & set(other), key=lambda n: int(n.rsplit('_', 1)[1])):
                grid = np.arange(0, other[name][1]['cut_g'] + args.grid, args.grid)
                series[f'{rung}/mix/{name}'] = {v: timeline(swarm_runs[name][0][v] + other[name][0][v], vectors, grid, key='g')
                                                for v in ('primary', 'solving_only')}
        del vectors
    curves, summary = {}, {}
    for rung in SEEDS:
        for arm in (*ARMS, 'mix'):
            rs = [v for k, v in series.items() if k.startswith(f'{rung}/{arm}/')]
            if rs:
                curves[f'{rung}/{arm}'] = {v: mean_curve([r[v] for r in rs], 20 if arm == 'mix' else 10) for v in rs[0]}
        per, marks = {}, {}
        for arm in ARMS:
            fs = {k.rsplit('/', 1)[1]: f for k, f in facts.items() if k.startswith(f'{rung}/{arm}/')}
            if not fs:
                continue
            barriers = [f['barrier_g'] for f in fs.values() if f['barrier_g'] is not None]
            marks[arm] = {'first_fork_g': st.mean(f['forks_g'][0] for f in fs.values()),
                          'last_fork_g': st.mean(f['forks_g'][-1] for f in fs.values()),
                          'barrier_g': st.mean(barriers) if barriers else None, 'end_g': st.mean(f['cut_g'] for f in fs.values())}
            for name, f in fs.items():
                twin = facts.get(f'{rung}/swarm/{name}')
                b, e = f['barrier_g'] if f['barrier_g'] is not None else twin and twin['barrier_g'], f['cut_g']
                for view, rows in series[f'{rung}/{arm}/{name}'].items():
                    per.setdefault(view, {}).setdefault(arm, {})[name] = {
                        'prelude': window_mean(rows, 0, f['forks_g'][0]), 'after_fork': window_mean(rows, f['forks_g'][0], e),
                        **({'after_barrier': window_mean(rows, b, e), 'post_barrier': window_mean(rows, b, b + args.post),
                            'later': window_mean(rows, b + args.post, e)} if b is not None else
                           {'after_barrier': None, 'post_barrier': None, 'later': None})}
        paired = {}
        for view, arms in per.items():  # swarm minus the comparison arm per seed, periods from the swarm's barrier
            for name in sorted(set(arms.get('swarm', {})) & set(arms.get(BASE, {})), key=lambda n: int(n.rsplit('_', 1)[1])):
                a, b = arms['swarm'][name], arms[BASE][name]
                paired.setdefault(view, {})[name] = {k: (a[k] - b[k]) if None not in (a[k], b[k]) else None
                                                     for k in ('post_barrier', 'later')}
        if marks:
            summary[str(rung)] = {'marks': marks, 'per_run': per, 'paired': paired}
    receipts = [read_json(p) for p in (out/'embedding-requests').glob('*.response.json')]
    data = {'params': {'baseline_arm': BASE, 'first': args.first, 'step': args.step, 'width': args.width, 'grid_tokens': args.grid,
                       'fine': args.fine, 'post_barrier_tokens': args.post,
                       'vectors': 'random (offline check)' if args.random_vectors else f'qwen3-embedding-4b via {PROVIDER} (deepinfra/us)'},
            'series': series, 'canonical': canonical, 'curves': curves, 'facts': facts, 'summary': summary,
            'embedding_rub': sum((r.get('usage') or {}).get('cost_rub') or 0 for r in receipts),
            'embedding_usd': sum((r.get('usage') or {}).get('cost') or 0 for r in receipts if 'cost_rub' not in (r.get('usage') or {}))}
    write_json(out/'covert.json', data)
    return data


INK, INK2, MUTED, GRID = '#0b0b0b', '#52514e', '#8a8984', '#e9e8e4'
