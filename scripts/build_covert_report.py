def svg(path, alt):
    return f'<img alt="{html.escape(alt)}" src="data:image/svg+xml;base64,{base64.b64encode(Path(path).read_bytes()).decode()}">'


def stats(d):
    rungs = rungs_of(d)
    def paired(view, period):
        return [x[period] for r in rungs for x in d['summary'][str(r)]['paired'].get(view, {}).values() if x[period] is not None]
    chat = paired('primary', 'post_barrier')
    solving = paired('solving_only', 'post_barrier') + paired('solving_only', 'later')
    rows = []
    for r in rungs:
        s = d['summary'][str(r)]
        pre = [v['prelude'] for v in s['per_run']['primary'].get('swarm', {}).values() if v['prelude'] is not None]
        cells = []
        for view, period in (('primary', 'post_barrier'), ('solving_only', 'post_barrier'), ('solving_only', 'later')):
            v = [x[period] for x in s['paired'].get(view, {}).values() if x[period] is not None]
            cells.append((st.mean(v), sum(x > 0 for x in v), len(v)) if v else None)
        rows.append((r, st.mean(pre) if pre else None, cells))
    return chat, solving, rows


