def style(ax):
    ax.grid(color=GRID, lw=.6); ax.set_axisbelow(True)
    for s in ('top', 'right'):
        ax.spines[s].set_visible(False)
    ax.tick_params(length=0)


def activity(ax, f):
    for a, bars in f['activity'].items():
        for g0, g1, s in bars:
            ax.barh(int(a), (g1 - g0)/1e3, left=g0/1e3, height=.72, color=STAGES.get(s, '#cccccc'), lw=0)
    ax.set_yticks(range(1, len(f['activity']) + 1)); ax.tick_params(axis='y', labelsize=7); ax.invert_yaxis()


def rungs_of(d):
    return [r for r in SEEDS if str(r) in d['summary']]


def lines(ax, d, rung, view, metric, arms):
    """Mean over seeds (band: min-max) of one metric for the given arms; returns the plotted values."""
    vals = []
    x_max = max(v['end_g'] for v in d['summary'][str(rung)]['marks'].values())*1.02
    for arm in arms:
        color = (ARMS.get(arm) or MIX)[1]
        p = [q for q in d['curves'].get(f'{rung}/{arm}', {}).get(view, []) if q['g'] <= x_max and q.get(metric) is not None]
        x = [q['g']/1e3 for q in p]
        if arm != 'mix':
            ax.fill_between(x, [q[f'{metric}_min'] for q in p], [q[f'{metric}_max'] for q in p], color=color, alpha=.13, lw=0)
        ax.plot(x, [q[metric] for q in p], color=color, lw=1.1 if arm == 'mix' else 1.5, ls=(0, (1, 1.2)) if arm == 'mix' else '-')
        vals += [q[k] for q in p for k in (f'{metric}_min', f'{metric}_max') if arm != 'mix'] + [q[metric] for q in p]
    return vals, x_max


def marks(ax, m):
    """Chat phase 1 of the swarm (shaded) and the barrier of every arm that has one (dashed)."""
    ax.axvspan(m['swarm']['first_fork_g']/1e3, m['swarm']['barrier_g']/1e3, color=SWARM[1], alpha=.06, lw=0)
    for arm, (_, color) in ARMS.items():
        if arm in m and m[arm]['barrier_g'] is not None:
            ax.axvline(m[arm]['barrier_g']/1e3, color=color, lw=.9, ls=(0, (4, 2)))


def legend(fig, y=.94, ncol=5):
    handles = [plt.Line2D([], [], color=SWARM[1], lw=1.8), plt.Line2D([], [], color=ARMS[BASE][1], lw=1.8),
               plt.Line2D([], [], color=MIX[1], lw=1.4, ls=(0, (1, 1.2))),
               plt.Rectangle((0, 0), 1, 1, color=SWARM[1], alpha=.12), plt.Line2D([], [], color=MUTED, lw=.9, ls=(0, (4, 2)))]
    fig.legend(handles, [SWARM[0], ARMS[BASE][0], MIX[0], 'Chat phase 1 (swarm)', 'Barrier'], loc='lower center', ncol=ncol,
               frameon=False, bbox_to_anchor=(.5, y), fontsize=8)


def fig_r(d, path):
    """R of the current vectors, mean over seeds (band: min-max), all windows and solving only, per rung."""
    rungs = rungs_of(d)
    fig, axes = plt.subplots(2, len(rungs), figsize=(3.3*len(rungs), 5.6), squeeze=False, sharex='col', sharey='col',
                             gridspec_kw=dict(hspace=.12, wspace=.18))
    for j, rung in enumerate(rungs):
        m = d['summary'][str(rung)]['marks']
        for i, (view, vname) in enumerate(VIEWS):
            ax = axes[i, j]
            marks(ax, m)
            vals, x_max = lines(ax, d, rung, view, 'R', (*ARMS, 'mix'))
            style(ax); ax.set_xlim(0, x_max/1e3)
            if vals:
                ax.set_ylim(min(vals) - .02, max(vals) + .02)
            if j == 0:
                ax.set_ylabel(f'{vname}\nR', color=INK, fontsize=9)
            if i == 0:
                ax.set_title(f'Rung {rung} · {LABELS[rung]}', fontsize=9, color=INK, loc='left')
        if j == 0:
            c = [q for q in d['curves'].get(f'{rung}/swarm', {}).get('primary', [])
                 if m['swarm']['barrier_g'] <= q['g'] <= m['swarm']['barrier_g'] + 15e3]
            if c:
                top = max(c, key=lambda q: q['R'])
                axes[0, 0].annotate('chat text\nin the windows', xy=(top['g']/1e3, top['R']), xytext=(top['g']/1e3 + x_max/1e3*.1, top['R'] + .03),
                                    fontsize=7.5, color=INK2, arrowprops=dict(arrowstyle='-', color=MUTED, lw=.7))
    legend(fig, ncol=5 if len(rungs) > 2 else 3)
    fig.supxlabel('Tokens generated by all agents of the run so far, thousands', fontsize=9, color=INK2, y=.01)
    fig.savefig(path, bbox_inches='tight'); plt.close(fig)


def fig_geom(d, path, view='solving_only'):
    """Spread across the mean direction and effective dimension, solving-only windows, per rung."""
    rungs = rungs_of(d)
    fig, axes = plt.subplots(2, len(rungs), figsize=(3.3*len(rungs), 5.6), squeeze=False, sharex='col',
                             gridspec_kw=dict(hspace=.12, wspace=.22))
    for j, rung in enumerate(rungs):
        m = d['summary'][str(rung)]['marks']
        for i, (metric, label) in enumerate((('var_perp', 'spread across\nthe mean direction'), ('eff_dim', 'effective\ndimension'))):
            ax = axes[i, j]
            marks(ax, m)
            _, x_max = lines(ax, d, rung, view, metric, (*ARMS, 'mix'))
            style(ax); ax.set_xlim(0, x_max/1e3)
            if j == 0:
                ax.set_ylabel(label, color=INK, fontsize=9)
            if i == 0:
                ax.set_title(f'Rung {rung} · {LABELS[rung]}', fontsize=9, color=INK, loc='left')
    legend(fig, ncol=5 if len(rungs) > 2 else 3)
    fig.supxlabel('Tokens generated by all agents of the run so far, thousands', fontsize=9, color=INK2, y=.01)
    fig.savefig(path, bbox_inches='tight'); plt.close(fig)


def fig_paired(d, path):
    """Swarm minus baseline R per seed (same prelude, same problems), four comparisons per rung."""
    rungs = rungs_of(d)
    cats = [(v, p) for v, _ in VIEWS for p, _ in PERIODS]
    vals = [x[p] for r in rungs for v, p in cats for x in d['summary'][str(r)]['paired'].get(v, {}).values() if x[p] is not None]
    lim = max(abs(v) for v in vals)*1.25 if vals else .05
    fig, axes = plt.subplots(1, len(rungs), figsize=(3.3*len(rungs), 3.1), squeeze=False, sharey=True, gridspec_kw=dict(wspace=.12))
    for j, rung in enumerate(rungs):
        ax = axes[0, j]
        ax.axvspan(1.5, 3.5, color='#f1f0ec', lw=0)
        ax.axhline(0, color=INK, lw=.8)
        for k, (view, period) in enumerate(cats):
            v = [x[period] for x in d['summary'][str(rung)]['paired'].get(view, {}).values() if x[period] is not None]
            color = ARMS['swarm'][1] if view == 'primary' else INK2
            ax.scatter([k + o for o in (-.15, -.05, .05, .15)[:len(v)]], v, s=22, color=color, edgecolor='white', lw=.8, zorder=3)
            if v:
                ax.plot([k - .25, k + .25], [st.mean(v)]*2, color=INK, lw=1.2, zorder=4)
