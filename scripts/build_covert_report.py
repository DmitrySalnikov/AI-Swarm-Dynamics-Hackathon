"""Report on the covert-channel experiment (covert-channel-v2): frozen agent vectors on a swarm-token axis, swarm vs baseline.

For every rung, arm and run (swarm_pipeline.covert_channel): every agent's whole generated stream (prelude problem,
chat messages, the problem it took; the baseline: prelude problem, then the problem its swarm twin took) is cut into
vector updates (swarm_pipeline.frozen_vectors: first after 1000 tokens, then every 500 tokens, window of the last 1000
tokens; token times from the delta journal), embedded, and R of the current (frozen) vectors is taken at every vector
update (canonical, in covert.json) and every --grid swarm tokens (tokens generated by all agents of the run so far;
waiting does not advance it) for the figures. Primary view: reasoning + visible replies; visible view: replies only.
Curves: mean over the runs of an arm; band: min-max over runs. The comparison arm is --baseline-arm: `baseline` shares
the prelude with its swarm twin (identical text and times, so the curves coincide until the first agent opens the
chat) and reaches its barrier earlier on the swarm-token axis, because it writes no messages; `independent` generates
its own prelude and solves set-B problems without waiting (no barrier of its own: the swarm's barrier marks the
comparison periods) and is cut at its swarm twin's end. Every point also has var_perp (spread across the mean
direction) and eff_dim (participation ratio), frozen_vectors.geometry. Mix: the twenty agents of a swarm run and its
comparison run with the same seed in one vector space (half of the population is noise for the swarm signal). Solving
only: windows wholly inside one problem.

  python scripts/build_covert_report.py --dry-run          # vector updates, uncached windows and estimated embedding cost
  python scripts/build_covert_report.py --random-vectors   # offline check: random unit vectors instead of embeddings
  POLZAAI_API_KEY=... python scripts/build_covert_report.py
  python scripts/build_covert_report.py --html-only        # figures and HTML again from covert.json
  python scripts/build_covert_report.py --baseline-arm baseline   # the covert-channel-v2 baseline (report/)
Outputs in <out> (default <root>/report-independent/, <root>/report/ for the v2 baseline): covert.json,
windows/*.jsonl, figures, covert.html.
"""
