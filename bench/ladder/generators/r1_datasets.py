"""Rung 1 (different fields) from datasets and dataset-style generators.

- SARA v1 tax cases (law): statutes + p cases; answers re-read from the Prolog test of each case (dataset-only).
- FinanceMath bundle (finance, reserve): answers from the dataset, verified by running each python_solution
  in the sandbox of fetch_sources.run_snippet.
- Reasoning Gym zebra_puzzles (logic) and calendar_arithmetic (calendar): generated by reasoning-gym (lazy import,
  needs `--with reasoning-gym`); verified by an own brute-force solver / numpy.busday_count.
- Shortest paths in the style of CLRS-Text (algorithms): own generator; Dijkstra vs Bellman-Ford.
"""
