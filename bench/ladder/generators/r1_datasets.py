SOURCES = Path(__file__).resolve().parents[1] / "sources"
RG_URL = "https://github.com/open-thought/reasoning-gym"


@cache
def load(name):
    return json.loads((SOURCES / name).read_text())


# ---------- SARA: US tax law cases ----------

def make_sara(p, rng):
    src = load("sara.json")
    cases = rng.sample(src["cases"], p)
    statutes = "\n\n".join(src["statutes"].values())
    body = "\n\n".join(f"Case {i}.\n{c['text']}\nQuestion: {c['question']}" for i, c in enumerate(cases, 1))
    prompt = ("The following sections of the US Internal Revenue Code (simplified, as used in the SARA statutory "
              "reasoning dataset) are the only law that applies. The total tax of a person is the income tax "
              "imposed by section 1 plus the excise tax imposed by section 3301 (if any).\n\n"
              f"=== STATUTES ===\n{statutes}\n=== END OF STATUTES ===\n\n"
              f"Apply these statutes to each of the following {p} independent case(s).\n\n{body}\n\n"
              f"Give the final answer as a comma-separated list of {p} tax amount(s) in dollars, in case order, "
              "each rounded to the nearest dollar and written as a plain integer (no $ sign, no thousands "
              "separators).")
    return dict(prompt=prompt, answer=",".join(str(c["answer"]) for c in cases),
                check={"type": "list", "rel_tol": 0.005}, data={"cases": [c["case"] for c in cases]})


def verify_sara(data):
    by_name = {c["case"]: c for c in load("sara.json")["cases"]}
    return ",".join(re.fullmatch(r":- tax\(\w+,\d+,(\d+)\)\.", by_name[n]["prolog_test"])[1] for n in data["cases"])


# ---------- FinanceMath bundle (reserve) ----------

def make_finmath(p, rng):
    picks = rng.sample(load("financemath.json")["pool"], p)
    parts = [f"Below are {p} independent finance problems. Solve each of them.\n"]
    for i, x in enumerate(picks, 1):
        parts.append(f"Problem {i}.\n{x['question'].strip()}" + "".join(f"\n\n{t.strip()}" for t in x["tables"]) + "\n")
    parts.append(f"Give the final answer as a comma-separated list of {p} numbers, one per problem in order. "
                 "Write each as a plain decimal number: monetary amounts in the units used by the problem, "
                 "percentages as a number of percent (e.g. 7.8 for 7.8%), no units, no currency symbols, "
                 "no thousands separators.")
    return dict(prompt="\n".join(parts), answer=",".join(x["ground_truth"] for x in picks),
                check={"type": "list", "rel_tol": 0.01}, data={"question_ids": [x["question_id"] for x in picks]})


def verify_finmath(data):
    from fetch_sources import run_snippet
    by_id = {x["question_id"]: x for x in load("financemath.json")["pool"]}
    return ",".join(repr(run_snippet(by_id[q]["python_solution"])) for q in data["question_ids"])


# ---------- Reasoning Gym: zebra puzzles ----------

RG_VERSION = "0.1.19"  # generated tasks depend on the library version


def _check_rg():
    import importlib.metadata
    v = importlib.metadata.version("reasoning-gym")
    assert v == RG_VERSION, f"reasoning-gym {v} installed, tasks were built with {RG_VERSION} (uv run --with reasoning-gym=={RG_VERSION})"


def make_zebra(p, rng):
    from random import Random
    _check_rg()
    from reasoning_gym.logic.contrib.logic_puzzle.generate import generate_puzzle
    seed = rng.randrange(2**31)
    # same calls as reasoning_gym.logic.zebra_puzzles.ZebraDataset(seed=seed)[0], keeping the Puzzle object
    instance, puzzle = generate_puzzle(Random(seed), p, p)
    text = str(puzzle)
    rows = instance["solution"]["table_rows"]
    assert instance["solution"]["table_header"][1] == "Name"
    names = [r[1] for r in rows]
    val = lambda lit: [type(lit).__name__, lit.name]
    clues = []
    for c in sorted(puzzle.clues):
        kind = type(c).__name__
        clues.append([kind, val(c.value), c.house] if hasattr(c, "house") else [kind, val(c.value1), val(c.value2)])
    cats = {cls.__name__: sorted(lit.name for lit in puzzle.literals if isinstance(lit, cls))
            for cls in puzzle.element_classes}
    prompt = (text + f"\nWho lives in each house? Give the final answer as a comma-separated list of the {p} "
              f"names (as spelled in the list of names) of the people in houses 1, 2, ..., {p} in this order.")
    return dict(prompt=prompt, answer=",".join(names), check={"type": "list"},
                data={"rg_seed": seed, "houses": p, "categories": cats, "clues": clues})


def _clue_ok(kind, a, b, k):
    if kind == "found_at":
        return a == b
    if kind == "not_at":
        return a != b
    return {"same_house": a == b, "consecutive": b - a == 1, "beside": abs(a - b) == 1, "left_of": a < b,
            "right_of": a > b, "one_between": abs(a - b) == 2, "two_between": abs(a - b) == 3}[kind]


def verify_zebra(data):
    """Own CSP search (one variable per attribute value, domain = houses, all-different per category, smallest
    domain first); checks that the solution is unique and returns its Name row."""
    k, cats = data["houses"], data["categories"]
    vars_ = [(c, m) for c in cats for m in cats[c]]
    unary = {v: set(range(1, k + 1)) for v in vars_}
    binary = {v: [] for v in vars_}
    for kind, v1, v2 in data["clues"]:
        a = tuple(v1)
        if isinstance(v2, int):
            unary[a] = {h for h in unary[a] if _clue_ok(kind, h, v2, k)}
        else:
            b = tuple(v2)
            binary[a].append((b, lambda x, y, kind=kind: _clue_ok(kind, x, y, k)))
            binary[b].append((a, lambda x, y, kind=kind: _clue_ok(kind, y, x, k)))
    pos, sols = {}, []

    def domain(v):
        used = {pos[(v[0], m)] for m in cats[v[0]] if (v[0], m) in pos}
        return [h for h in unary[v] - used if all(ok(h, pos[w]) for w, ok in binary[v] if w in pos)]

    def rec():
        if len(sols) > 1:
            return
        free = [v for v in vars_ if v not in pos]
        if not free:
            sols.append(dict(pos))
            return
        doms = {v: domain(v) for v in free}
        v = min(free, key=lambda u: len(doms[u]))
        for h in doms[v]:
            pos[v] = h
            rec()
            del pos[v]

    rec()
    assert len(sols) == 1, f"{len(sols)} solutions"
    by_house = {h: m for (c, m), h in sols[0].items() if c == "Name"}
    return ",".join(by_house[h].replace("_", " ") for h in range(1, k + 1))


# ---------- Reasoning Gym: calendar arithmetic (count business days / count a weekday) ----------

WEEKDAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


def make_calendar(k, rng):
    _check_rg()
    import reasoning_gym as rg
    year, seed = rng.randint(1990, 2035), rng.randrange(2**31)
    ds = rg.create_dataset("calendar_arithmetic", size=10 * k, seed=seed, year=year, offset_upper_bound=200,
                           tasks=["count_business_days", "count_days"])
    qs, answers = [], []
    for i in range(10 * k):
        it = ds[i]
        md = it["metadata"]
        if date.fromisoformat(md["end_date"]).year != year:   # RG prints `year` for both dates; skip year crossings
            continue
        q = {"task": md["task"], "start": md["start_date"], "end": md["end_date"], "rg_index": i}
        if md["task"] == "count_days":
            q["weekday"] = re.search(r"How many (\w+day)s|occurrences of (\w+day)|does (\w+day) occur",
                                     it["question"]).group(1, 2, 3)
            q["weekday"] = next(w for w in q["weekday"] if w)
        qs.append((it["question"].strip(), q))
        answers.append(it["answer"])
        if len(qs) == k:
            break
    assert len(qs) == k
    body = "\n".join(f"{i}. {t}" for i, (t, _) in enumerate(qs, 1))
    prompt = (f"Answer the following {k} calendar questions (Gregorian calendar; business days are Monday to "
              f"Friday, no holidays).\n\n{body}\n\nGive the final answer as a comma-separated list of {k} integers, "
              "one per question in order.")
    return dict(prompt=prompt, answer=",".join(answers), check={"type": "list", "rel_tol": 0},
                data={"rg_seed": seed, "year": year, "questions": [q for _, q in qs]})


def verify_calendar(data):
    import numpy as np
    out = []
    for q in data["questions"]:
        a, b = np.datetime64(q["start"]), np.datetime64(q["end"]) + np.timedelta64(1, "D")
        mask = "1111100" if q["task"] == "count_business_days" else \
            "".join("1" if w == q["weekday"] else "0" for w in WEEKDAYS)
        out.append(str(int(np.busday_count(a, b, weekmask=mask))))
    return ",".join(out)


# ---------- shortest paths (own generator in the style of CLRS-Text) ----------

def make_sp(n, rng, wmax=20):
    order = list(range(1, n))
    rng.shuffle(order)
    seen, edges = [0], {}
    for v in order:                              # random arborescence from 0: every vertex is reachable
        edges[(rng.choice(seen), v)] = rng.randint(1, wmax)
        seen.append(v)
    while len(edges) < round(2.5 * n):
        u, v = rng.randrange(n), rng.randrange(n)
        if u != v and (u, v) not in edges:
            edges[(u, v)] = rng.randint(1, wmax)
    elist = [[u, v, w] for (u, v), w in edges.items()]
    rng.shuffle(elist)
    adj = {u: [] for u in range(n)}
    for u, v, w in elist:
        adj[u].append((v, w))
    dist, pq = {0: 0}, [(0, 0)]
    while pq:
        d, u = heapq.heappop(pq)
        if d > dist[u]:
            continue
        for v, w in adj[u]:
            if d + w < dist.get(v, float("inf")):
                dist[v] = d + w
                heapq.heappush(pq, (d + w, v))
    lines = "\n".join(f"{u} -> {v} : {w}" for u, v, w in elist)
    prompt = (f"A weighted directed graph has {n} vertices numbered 0 to {n - 1} and the following {len(elist)} "
              f"directed edges, written `u -> v : w` (an edge from u to v of weight w):\n\n{lines}\n\n"
              f"Find the length of the shortest path from vertex 0 to every vertex (the distance to 0 itself is 0; "
              f"every vertex is reachable from 0). Give the final answer as a comma-separated list of {n} integers: "
              f"the distances to vertices 0, 1, ..., {n - 1} in this order.")
    return dict(prompt=prompt, answer=",".join(str(dist[v]) for v in range(n)), check={"type": "list", "rel_tol": 0},
                data={"n": n, "edges": elist})


def verify_sp(data):
    n, inf = data["n"], float("inf")
    d = [0] + [inf] * (n - 1)
    for _ in range(n - 1):                       # Bellman-Ford
        for u, v, w in data["edges"]:
            d[v] = min(d[v], d[u] + w)
    return ",".join(str(x) for x in d)


